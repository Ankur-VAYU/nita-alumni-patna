#!/usr/bin/env node
// Copies migrations/*.sql into src/db/migrations.generated.ts so the app can apply them on
// Cloudflare Workers, which have no file system. Run automatically before build and deploy.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = readdirSync(join(root, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const list = files.map((name) => ({ name, sql: readFileSync(join(root, 'migrations', name), 'utf8') }));
const out = `// Generated by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(list, null, 2)};\n`;
writeFileSync(join(root, 'src', 'db', 'migrations.generated.ts'), out);
console.log(`Bundled ${files.length} migration(s).`);
